/**
 * Что происходит один раз при подъёме сервера.
 *
 * Next вызывает register() однажды на процесс — до первого запроса и
 * независимо от того, откроет ли кто-нибудь страницу. Это единственное
 * место, где можно завести таймер обхода: маршрут API для этого не годится,
 * потому что он выполняется только тогда, когда к нему обратились, а весь
 * смысл автоматического сбора в том, чтобы к программе не обращались.
 *
 * Проверка runtime обязательна. Этот же файл Next загружает в окружении
 * Edge, где нет ни setInterval нужного вида, ни Prisma; без проверки сборка
 * падает на попытке затянуть туда клиент базы. Поэтому серверная часть
 * импортируется динамически и только под Node.
 */

export async function register(): Promise<void> {
  if (process.env.NEXT_RUNTIME !== 'nodejs') return;

  /*
   * Импорт внутри функции, а не сверху файла: статический импорт Prisma
   * попал бы в бандл Edge при любом значении NEXT_RUNTIME.
   */
  const { prisma } = await import('./lib/db');
  const { startScheduler } = await import('./server/scheduler');

  startScheduler(prisma);
}
