export type UiKey = keyof typeof UI;

/**
 * Переводчик, привязанный к языку.
 *
 * Возвращается функция, а не объект, чтобы в разметке строка была видна
 * как `t('scoringConfirm')` — и неверный ключ стал ошибкой компиляции,
 * а не пустой надписью в готовом интерфейсе.
 */
export function translator(locale: Locale) {
  return (key: UiKey): string => UI[key][locale];
}

/** Выбор нужного языка из двуязычной строки, пришедшей с сервера. */
export function pick(label: Label | null | undefined, locale: Locale): string {
  if (!label) return '';
  return label[locale];
}
