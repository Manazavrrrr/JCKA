/**
 * Словарь интерфейса.
 *
 * Двуязычие здесь не украшение: предметная область — государственный
 * контроль в Казахстане, и аналитик МИО работает с документами на двух
 * языках. Поэтому язык выбран как свойство всего приложения, а не как
 * переключатель отдельных надписей.
 *
 * Устройство словаря намеренно простое — плоская карта «ключ → две
 * строки». Типизация делает пропуск языка ошибкой компиляции, а тест
 * проверяет, что ни одна строка не осталась скопированной с русского
 * в казахскую без перевода.
 *
 * Названия факторов, статусов и зон здесь не дублируются: они живут
 * в core/domain/enums.ts рядом с самими перечислениями, потому что
 * приходят вместе с данными из API и должны совпадать в интерфейсе,
 * в журнале и в печатной карточке.
 */

