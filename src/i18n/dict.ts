/**
 * Имя cookie с выбранным языком.
 *
 * Лежит в этом модуле, а не рядом с чтением cookie на сервере, потому что
 * нужно обеим сторонам: сервер читает, переключатель в браузере пишет.
 * Модуль i18n/server.ts импортирует next/headers и в клиентский компонент
 * не годится.
 */
export const LOCALE_COOKIE = 'saq_locale';

export function isLocale(value: unknown): value is Locale {
  return value === 'ru' || value === 'kk';
}

