/**
 * Каталог внешних реестров: что можно проверить машиной, а что нельзя.
 *
 * Слой сбора отвечает на вопрос «кто и что рекламирует». Этот слой отвечает
 * на следующий вопрос — «а что про это говорит государство». Между ними
 * принципиальная разница в цене ошибки: реклама живёт в ленте и её всегда
 * можно перечитать, а ответ реестра получен один раз, на конкретную дату,
 * и завтра будет другим. Поэтому здесь важнее всего не удобство, а точное
 * указание, откуда взят каждый факт и когда.
 *
 * Содержимое этого файла — результат сплошной проверки порталов, а не
 * список ссылок из задания. Проверка дала три неприятных, но важных вывода,
 * и все три записаны здесь как свойства источников, а не спрятаны:
 *
 *   1. Разрешений МИО на привлечение денег дольщиков в открытых данных нет.
 *      Ни одного набора — ни на data.egov.kz, ни в каталоге по ведомствам.
 *      Разрешение видно только через веб-интерфейсы homeportal.kz, elicense.kz
 *      и qazreestr.kz, у которых открытого API нет.
 *
 *   2. Гарантий АО «Казахстанская жилищная компания» в открытых данных тоже
 *      нет. КЖК числится поставщиком данных на портале, но наборов с
 *      перечнем гарантированных объектов не публикует.
 *
 *   3. Реестр уведомлений о начале строительно-монтажных работ существует и
 *      по названию подходит идеально, но он заморожен в апреле 2021 года и
 *      покрывает только город Алматы. Подключить его — значит получить
 *      пустой ответ по Усть-Каменогорску и выдать его за проверку.
 *
 * Первые два вывода напрямую касаются фактора R1, который стоит дороже всех
 * остальных. И ровно на этот случай в модели риска с самого начала записано:
 * отсутствие доступа к реестру и ответ «нет данных» основанием для начисления
 * не являются. То есть недоступность реестра не превращается в балл — она
 * превращается в задачу аналитику проверить вручную и приложить выписку.
 *
 * Третий вывод — причина, по которой у источника есть состояние ARCHIVED.
 * Набор, замерший несколько лет назад, опаснее отсутствующего: он отвечает
 * бодро и пусто, и пустой ответ легко прочитать как «нарушений не найдено».
 *
 * Модуль чистый: ни Prisma, ни сети, ни текущего времени.
 */

