export interface RegistrySource {
  id: string;
  name: Label;
  /** Кто публикует. Нужно, чтобы аналитик понимал, с кого спрашивать. */
  authority: Label;
  accessMode: RegistryAccessMode;
  bearing: RegistryBearing;
  /** Что именно оттуда можно узнать. */
  provides: Label;
  /**
   * Машинное имя набора на портале. Заполнено только у OPEN_API и ARCHIVED;
   * у WEB_ONLY его нет, потому что набора не существует. Проверяется тестом.
   */
  dataset: string | null;
  /** Версия набора на портале. Идёт в пути запроса вместе с dataset. */
  datasetVersion: string | null;
  /** Адрес, по которому сказанное можно проверить руками. */
  reference: string;
  /**
   * Почему машинно нельзя или почему нельзя доверять. Обязательно заполнено
   * у WEB_ONLY и ARCHIVED, пусто у OPEN_API — это проверяется тестом, чтобы
   * ограничение нельзя было записать без объяснения.
   */
  limitation: Label | null;
  /** Как часто обновляется источник. Пусто, если неизвестно. */
  refreshed: Label | null;
}

