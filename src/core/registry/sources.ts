/** Источники, которые коннектор читает сам. */
export function machineReadableSources(): RegistrySource[] {
  return REGISTRY_SOURCES.filter((source) => source.accessMode === 'OPEN_API');
}

/** Источники, по которым выписку приносит аналитик. */
export function manualRegistrySources(): RegistrySource[] {
  return REGISTRY_SOURCES.filter((source) => source.accessMode === 'WEB_ONLY');
}

/**
 * Источники, проверенные и отклонённые. Отдельная выборка нужна, чтобы их
 * можно было показать списком: «мы это смотрели, вот почему не взяли».
 */
export function rejectedRegistrySources(): RegistrySource[] {
  return REGISTRY_SOURCES.filter((source) => source.accessMode === 'ARCHIVED');
}

/** Возвращает null, а не undefined, — как и findSource в слое сбора. */
export function findRegistrySource(id: string): RegistrySource | null {
  return REGISTRY_SOURCES.find((source) => source.id === id) ?? null;
}

/** Источники, относящиеся к одному вопросу — правовому основанию или застройщику. */
export function sourcesByBearing(bearing: RegistryBearing): RegistrySource[] {
  return REGISTRY_SOURCES.filter((source) => source.bearing === bearing);
}
