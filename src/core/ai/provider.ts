/**
 * Интерфейс провайдера разбора объявлений.
 *
 * Провайдер получает произвольный текст и список объектов реестра, а возвращает
 * результат по общей схеме. Два свойства интерфейса важны для оценки работы:
 *
 *   1. Вход — это текст, а не идентификатор заготовленного примера. Разбор
 *      работает на объявлении, которое проверяющий напишет сам при демонстрации;
 *      демо-данные не имеют никаких преимуществ перед новым текстом.
 *
 *   2. Выход провайдера не влияет на балл. Провайдер возвращает гипотезы,
 *      расчёт балла живёт в src/core/scoring и принимает только подтверждённые
 *      аналитиком факторы. Поэтому замена провайдера не может изменить ни одну
 *      оценку риска по уже проверенным объектам — результат воспроизводим.
 */

import type { AiProviderId, Label } from '../domain/enums';
import type { AnalysisResult } from './schemas';

/**
 * Объект реестра в том виде, в котором он нужен для сопоставления.
 *
 * Специально не Prisma-тип: ядро ИИ не должно зависеть от схемы БД,
 * благодаря этому его можно тестировать без базы.
 */
export interface ProjectCandidate {
  id: string;
  name: string;
  nameKk?: string | null;
  address?: string | null;
  developerName?: string | null;
  /** Телефоны из подтверждённых публикаций объекта — ещё один признак связи. */
  knownPhones?: readonly string[];
}

export interface AnalyzeInput {
  /** Текст объявления в исходном виде. Позиции цитат считаются по нему. */
  text: string;
  /** Заголовок, если платформа отдаёт его отдельно. */
  title?: string | null;
  /** Реестр для сопоставления. Пустой список — сопоставление не выполняется. */
  projects?: readonly ProjectCandidate[];
  /** Язык, на котором нужно вернуть основную подпись. Влияет только на UI. */
  locale?: 'ru' | 'kk';
}

export interface AiProvider {
  readonly id: AiProviderId;
  /** Человекочитаемое описание для панели «как это работает». */
  readonly description: Label;
  /** Доступен ли провайдер в текущей конфигурации. */
  isAvailable(): boolean;
  analyze(input: AnalyzeInput): Promise<AnalysisResult>;
}

