/**
 * Факторы, которые ИИ имеет право предложить.
 *
 * R1 и R4 отсутствуют сознательно, и это ключевое архитектурное решение
 * модуля:
 *
 *   - R1 требует установленного отсутствия правового основания. Это вывод
 *     из реестра и документов, а не из текста объявления. Никакой разбор
 *     текста не может подтвердить, что основания нет: в объявлении его
 *     просто могли не упомянуть. Разрешить ИИ предлагать R1 означало бы
 *     построить +35 баллов на отсутствии данных — ровно то, что ТЗ
 *     прямо запрещает.
 *
 *   - R4 требует зарегистрированного коллективного обращения. Источник
 *     этого факта — журнал обращений, а не публикация.
 *
 * Вместо гипотезы по R1 движок возвращает отдельный пункт «проверить
 * правовое основание в реестре» в списке проверок.
 */
