/**
 * Поиск объявлений по словам, а не по перечню аккаунтов.
 *
 * Чем это отличается от прогона по профилю. Прогон по профилю отвечает на
 * вопрос «что публикует вот этот застройщик» — и предполагает, что застройщик
 * уже известен. Но застройщик, которого стоит проверить, обычно тем и
 * отличается, что его ещё нет ни в одном перечне: он не сдавал объект, не
 * попадал в сводку, и узнать о нём орган может только из его же рекламы.
 * Перечень аккаунтов — это список тех, о ком уже знают. Искать в нём
 * неизвестное бессмысленно по устройству.
 *
 * Поэтому здесь вход другой: не имя аккаунта, а слово. Аккаунты становятся
 * результатом поиска, а не его условием, и перечень наполняется сам.
 *
 * Как это устроено технически и почему именно так. Instagram не даёт искать
 * по словам в открытом виде, но страница хештега — обычная публичная
 * страница вида instagram.com/explore/tags/<тег>/, и тот же сборщик, который
 * читает профиль, читает и её. Это решение стоит назвать прямо: вместо
 * второго актора с другим ответом, другой ценой и другим разбором
 * используется тот же самый — меняется только адрес. Отсюда три следствия,
 * и все три хорошие: разбор ответа один на оба режима и уже проверен
 * тестами; цена одна и уже показана в интерфейсе; поведение без ключа
 * (работа на сохранённом образце с честной пометкой) наследуется целиком.
 *
 * Чего этот способ не умеет. Он находит то, что помечено хештегом.
 * Объявление без хештегов не найдётся, и это ограничение надо держать в
 * голове: поиск по словам расширяет охват, но не делает его полным. Прогон
 * по известному профилю остаётся — у него другая задача.
 *
 * Цена растёт не так, как в прогоне по профилю, и это главная ловушка
 * режима. Сборщик берёт resultsLimit на каждый адрес, а адресов здесь
 * столько, сколько слов в поиске. Пять слов по двадцать публикаций — это сто
 * результатов, а не двадцать. Поэтому стоимость обхода считается как
 * произведение, а не как потолок одного прогона, и потолок на обход стоит
 * отдельный.
 *
 * Модуль чистый: ни сети, ни Prisma, ни текущего времени.
 */

import type { Label } from '../domain/enums';

