/**
 * Собирает вход сборщика для обхода по тегам.
 *
 * Отличие от прогона по профилю — только в адресах: вместо одного профиля
 * несколько страниц тегов. Остальное совпадает, и это не совпадение, а
 * причина, по которой выбран именно такой способ поиска.
 *
 * Закреплённые публикации пропускаются так же, как в прогоне по профилю: на
 * странице тега сверху висит «популярное», которое меняется редко и на
 * каждом обходе приходило бы заново, занимая платные результаты.
 */
export function instagramHashtagInput(
  tags: readonly string[],
  options: { limitPerTag?: number; newerThan?: string | null } = {},
): InstagramScraperInput {
  const unique = Array.from(new Set(tags)).slice(0, MAX_ACTIVE_QUERIES);

  const input: InstagramScraperInput = {
    directUrls: unique.map(hashtagExploreUrl),
    resultsType: 'posts',
    resultsLimit: limitPerTagWithinWalk(
      unique.length,
      options.limitPerTag ?? DEFAULT_HASHTAG_LIMIT,
    ),
    skipPinnedPosts: true,
  };

  const newerThan = options.newerThan?.trim();
  if (newerThan && newerThan.length > 0) input.onlyPostsNewerThan = newerThan;

  return input;
}

