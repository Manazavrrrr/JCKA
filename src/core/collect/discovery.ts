// Поисковое слово
// ---------------------------------------------------------------------------

/**
 * Хештег: буквы любого алфавита, цифры и подчёркивание.
 *
 * Кириллица допускается намеренно — по-русски и по-казахски объявления
 * помечают кириллическими тегами, и отбросить их значило бы оставить поиск
 * без половины рынка. Два знака снизу: однобуквенный тег ловит всё подряд.
 */
const HASHTAG_PATTERN = /^[\p{L}\p{N}_]{2,100}$/u;

/**
 * Почему слово не годится в поиск. Причина отделена от текста: по ней
 * ветвится проверка ввода, текст идёт аналитику.
 */
export type HashtagProblem = 'EMPTY' | 'TOO_SHORT' | 'BAD_CHARACTERS';

export interface HashtagResult {
  /** Готовый тег без решётки, или null, если слово не годится. */
  tag: string | null;
  problem: HashtagProblem | null;
  /**
   * Было ли слово изменено при приведении. Если да, интерфейс обязан
   * показать результат: аналитик ввёл «жк усть каменогорск», искаться будет
   * «жкустькаменогорск», и узнать об этом он должен до прогона, а не по
   * пустому результату.
   */
  changed: boolean;
}

/**
 * Приводит введённое к виду хештега.
 *
 * Пробелы склеиваются, а не отвергаются: в хештегах пробелов не бывает, и
 * «усть каменогорск» люди пишут как #устькаменогорск. Но склейка объявляется
 * через changed — молча превращать введённое в другое этот проект себе не
 * позволяет нигде.
 */
export function normalizeHashtag(input: string): HashtagResult {
  const original = input.trim();
  if (original.length === 0) return { tag: null, problem: 'EMPTY', changed: false };

  let value = original;
  // Аналитик копирует из браузера адрес страницы тега целиком.
  value = value.replace(/^https?:\/\//i, '');
  value = value.replace(/^(?:www\.)?instagram\.com\/explore\/tags\//i, '');
  value = value.split(/[/?#]/).filter((part) => part.length > 0)[0] ?? '';
  value = value.replace(/^#/, '');
  // Пробелы и дефисы склеиваются: в теге их не бывает.
  value = value.replace(/[\s\-—–]+/g, '');
  value = value.toLowerCase();

  const changed = value !== original;

  if (value.length === 0) return { tag: null, problem: 'EMPTY', changed };
  if (value.length === 1) return { tag: null, problem: 'TOO_SHORT', changed };
  if (!HASHTAG_PATTERN.test(value)) return { tag: null, problem: 'BAD_CHARACTERS', changed };

  return { tag: value, problem: null, changed };
}

