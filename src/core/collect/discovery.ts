/** Адрес публичной страницы хештега — то, что читает сборщик. */
export function hashtagExploreUrl(tag: string): string {
  return `https://www.instagram.com/explore/tags/${encodeURIComponent(tag)}/`;
}

// ---------------------------------------------------------------------------
// Потолок обхода
// ---------------------------------------------------------------------------

/**
 * Сколько публикаций брать с одного тега за обход.
 *
 * Меньше, чем с профиля, и намеренно: тегов в обходе несколько, и каждый
 * умножает счёт. Десять свежих публикаций по тегу — этого хватает, чтобы
 * заметить появление новой рекламы, а не чтобы изучить рынок.
 */
export const DEFAULT_HASHTAG_LIMIT = 10;

/**
 * Жёсткий потолок на весь обход, в результатах.
 *
 * Тот же приём, что MAX_POSTS_LIMIT у одиночного прогона, но на уровень
 * выше. Там потолок защищал от лишнего нуля в поле; здесь — от умножения:
 * десять тегов по сто публикаций стоят 2,70 $ за один обход, а обходов в
 * сутках много. Дневной предел расхода (budget.ts) ловит это следом, но
 * ловить дважды дешевле, чем один раз: предел — величина настраиваемая, а
 * потолок — нет.
 */
export const MAX_RESULTS_PER_WALK = 100;

/** Сколько поисковых слов может быть включено одновременно. */
export const MAX_ACTIVE_QUERIES = 10;

/**
 * Сколько результатов запросит обход по этим тегам.
 *
 * Произведение, а не сумма лимитов: сборщик применяет resultsLimit к каждому
 * адресу отдельно. На этой арифметике легко ошибиться в меньшую сторону и
 * удивиться счёту, поэтому она вынесена в отдельную названную функцию и
 * проверяется тестом.
 */
export function plannedWalkResults(tagCount: number, limitPerTag: number): number {
  const tags = Math.max(0, Math.trunc(tagCount));
  if (tags === 0) return 0;
  return Math.min(MAX_RESULTS_PER_WALK, tags * clampPostsLimit(limitPerTag));
}

/**
 * Сколько брать с тега, чтобы обход целиком уложился в потолок.
 *
 * Возвращает ноль, если тегов больше, чем результатов в потолке: просить
 * «по нулю с каждого» бессмысленно, и вызывающий должен в этом случае
 * сократить список слов, а не делать вид, что обход состоялся.
 */
export function limitPerTagWithinWalk(tagCount: number, desired: number): number {
  const tags = Math.max(0, Math.trunc(tagCount));
  if (tags === 0) return 0;
  const wanted = clampPostsLimit(desired);
  return Math.min(wanted, Math.floor(MAX_RESULTS_PER_WALK / tags));
}

