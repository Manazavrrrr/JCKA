/**
 * Признаки привязки к месту.
 *
 * Перечень нужен не программе, а проверке: тест требует, чтобы каждое
 * включённое по умолчанию слово содержало один из этих корней. Без такой
 * проверки утверждение «по умолчанию включены только слова с привязкой к
 * месту» осталось бы обещанием в комментарии, а обещание в комментарии
 * живёт ровно до первой правки списка.
 */
export const GEO_MARKERS: readonly string[] = [
  'устькаменогорск',
  'оскемен',
  'өскемен',
  'вко',
  'шқо',
];

/** Есть ли в слове привязка к месту. */
export function hasGeoMarker(tag: string): boolean {
  return GEO_MARKERS.some((marker) => tag.includes(marker));
}
