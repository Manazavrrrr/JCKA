// ---------------------------------------------------------------------------
// Источник
// ---------------------------------------------------------------------------

export interface CollectSource {
  id: string;
  name: Label;
  /** Площадка, которая проставится публикации, созданной из этого источника. */
  platform: Platform;
  accessMode: SourceAccessMode;
  /** Чем именно читается источник или как вносится вручную. */
  method: Label;
  /**
   * Почему автоматически нельзя. Заполнено у всех MANUAL_ONLY и пусто
   * у AUTO — это проверяется тестом, чтобы ограничение нельзя было
   * добавить без объяснения.
   */
  limitation: Label | null;
  /** Куда посмотреть, чтобы проверить сказанное. */
  reference: string | null;
  /** Чего этот источник не покажет даже при автоматическом сборе. */
  blindSpot: Label | null;
  /**
   * Сколько стоит прогон. Заполнено у всех KEY_REQUIRED и пусто у
   * остальных: платный источник обязан назвать цену до запуска, а не
   * после. Проверяется тестом.
   */
  cost: Label | null;
  /**
   * Правовая оговорка: чем именно сбор из этого источника неудобен и
   * кто принимает решение его включить. Заполнена у всех KEY_REQUIRED.
   * Отличается от limitation: там — «автоматически нельзя вовсе», здесь
   * — «технически можно, но решает орган».
   */
  caveat: Label | null;
}

