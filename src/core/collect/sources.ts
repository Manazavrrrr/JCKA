/** Источник по идентификатору. */
export function findSource(id: string): CollectSource | null {
  return COLLECT_SOURCES.find((source) => source.id === id) ?? null;
}

/** Источники, которые читает коннектор. */
export function autoSources(): CollectSource[] {
  return COLLECT_SOURCES.filter((source) => source.accessMode === 'AUTO');
}

/** Источники, которые заполняет аналитик, — вместе с причиной. */
export function manualSources(): CollectSource[] {
  return COLLECT_SOURCES.filter((source) => source.accessMode === 'MANUAL_ONLY');
}

/** Источники, которым нужен ключ, — вместе с ценой и оговоркой. */
export function keyRequiredSources(): CollectSource[] {
  return COLLECT_SOURCES.filter((source) => source.accessMode === 'KEY_REQUIRED');
}
