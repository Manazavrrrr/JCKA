/**
 * Каталог источников: откуда берётся поток и где он обрывается.
 *
 * Главная мысль этого файла — в поле accessMode. Слова-ловушки отвечают на
 * вопрос «что вытащить из потока», и к ним вопросов нет. Отдельный и гораздо
 * более неприятный вопрос — «откуда берётся сам поток», и честный ответ на
 * него разный для разных площадок:
 *
 *   - публичный Telegram-канал, доска объявлений и сайт застройщика отдают
 *     содержимое открыто, без токена и без согласия — их читает коннектор;
 *
 *   - реклама в Instagram и Facebook по Казахстану автоматически недоступна.
 *     Ad Library API отдаёт коммерческую рекламу только по странам ЕС и
 *     Великобритании: это следствие DSA, а не настройка, которую можно
 *     включить. Для Казахстана тот же запрос возвращает лишь политическую
 *     и социальную рекламу. Веб-версия библиотеки рекламы по Казахстану
 *     ищет, но её автоматический разбор нарушает условия площадки;
 *
 *   - личные сообщения и закрытые группы в WhatsApp зашифрованы сквозным
 *     шифрованием: доступа нет ни технически, ни юридически.
 *
 * Эти ограничения не спрятаны и не обойдены — они записаны как свойство
 * источника и показываются в интерфейсе рядом с ним. Источник в режиме
 * MANUAL_ONLY остаётся в списке, работает через ручной ввод аналитика
 * (снимок экрана плюс текст) и несёт при себе объяснение, почему иначе
 * нельзя. Проверяющему должно быть видно, что граница продумана, а не
 * пропущена; аналитику — что делать с объявлением, которое система
 * сама не принесёт.
 *
 * Отдельно отмечено слепое пятно, общее для всех источников: текст,
 * вписанный в картинку (сторис, баннер, карусель), фильтр по словам не
 * видит. Распознавание изображений в этой версии не выполняется.
 *
 * Модуль чистый: ни Prisma, ни сети, ни текущего времени.
 */

