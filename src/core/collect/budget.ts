// Решение
// ---------------------------------------------------------------------------

/**
 * Почему платный прогон не состоялся.
 *
 * Причина отделена от текста намеренно: по ней ветвится планировщик (отказ по
 * лимиту — это не сбой, обход продолжается бесплатными источниками), а текст
 * идёт в пометку прогона и на экран.
 */
export type BudgetVerdict =
  /** Денег хватает, прогон разрешён. */
  | 'ALLOWED'
  /** Предел выставлен в ноль: платный сбор выключен решением органа. */
  | 'DISABLED'
  /** Суточный предел уже исчерпан предыдущими прогонами. */
  | 'EXHAUSTED'
  /** Остаток есть, но этого прогона не хватит целиком. */
  | 'WOULD_EXCEED';

export interface BudgetDecision {
  verdict: BudgetVerdict;
  allowed: boolean;
  /** Потрачено с начала местных суток, доллары. */
  spentUsd: number;
  /** Сколько осталось до предела, доллары. Никогда не отрицательно. */
  remainingUsd: number;
  /** Во сколько обошёлся бы запрошенный прогон. */
  plannedUsd: number;
  /**
   * Сколько результатов умещается в остаток. Планировщику этого достаточно,
   * чтобы уменьшить прогон вместо отказа — но уменьшение он обязан назвать.
   */
  affordableResults: number;
  note: Label;
}

/**
 * Пускать ли платный прогон.
 *
 * Отказ не уменьшает прогон молча. Уменьшить — дело вызывающего, и тогда он
 * обязан сказать, что уменьшил: прогон, тихо собравший семь публикаций вместо
 * двадцати, выглядит в истории как прогон, на котором в источнике нашлось
 * только семь. Это ровно та подмена, против которой построен остальной сбор.
 */
export function decideBudget(input: {
  /** Прогоны за последние сутки и шире — лишние отсеются по дате. */
  runs: readonly SpentRun[];
  /** Предел на сутки, доллары. */
  dailyBudgetUsd: number;
  /** Сколько результатов собирается запросить прогон. */
  plannedResults: number;
  now: Date;
}): BudgetDecision {
  const budgetCents = Math.round(clampDailyBudgetUsd(input.dailyBudgetUsd) * 100);
  const spentCents = Math.round(spentTodayUsd(input.runs, input.now) * 100);
  const plannedCents = Math.round(estimateRunCostUsd(input.plannedResults) * 100);

  const remainingCents = Math.max(0, budgetCents - spentCents);
  const affordableResults = maxAffordableResults(remainingCents / 100);

  const base = {
    spentUsd: spentCents / 100,
    remainingUsd: remainingCents / 100,
    plannedUsd: plannedCents / 100,
    affordableResults,
  };

  /*
   * Запятая, а не точка. Текст читает аналитик в Усть-Каменогорске, и
   * «0.27 $» в русском предложении читается как опечатка или как обрывок
   * кода. Разделитель здесь — часть перевода, а не формат числа.
   */
  const money = (cents: number) => (cents / 100).toFixed(2).replace('.', ',');

  if (budgetCents === 0) {
    return {
      ...base,
      verdict: 'DISABLED',
      allowed: false,
      note: {
        ru: 'Платный сбор выключен: дневной предел расходов выставлен в ноль. Бесплатные источники обойдены как обычно.',
        kk: 'Ақылы жинау өшірулі: тәуліктік шығын шегі нөлге қойылған. Тегін дереккөздер әдеттегідей аралады.',
      },
    };
  }

  if (remainingCents === 0) {
    return {
      ...base,
      verdict: 'EXHAUSTED',
      allowed: false,
      note: {
        ru: `Дневной предел расходов исчерпан: за сутки потрачено ${money(spentCents)} $ при пределе ${money(budgetCents)} $. Платный источник пропущен, бесплатные обойдены.`,
        kk: `Тәуліктік шығын шегі таусылды: тәулігіне ${money(spentCents)} $ жұмсалды, шегі ${money(budgetCents)} $. Ақылы дереккөз өткізіліп жіберілді, тегіндері аралады.`,
      },
    };
  }

  if (plannedCents > remainingCents) {
    return {
      ...base,
      verdict: 'WOULD_EXCEED',
      allowed: false,
      note: {
        ru: `Прогон на ${money(plannedCents)} $ не умещается в остаток дня: за сутки израсходовано ${money(spentCents)} $ из ${money(budgetCents)} $, осталось ${money(remainingCents)} $ — это ${affordableResults} публикаций. Платный источник пропущен.`,
        kk: `${money(plannedCents)} $ тұратын жүгіру күн қалдығына сыймайды: тәулігіне ${money(budgetCents)} $ ішінен ${money(spentCents)} $ жұмсалды, ${money(remainingCents)} $ қалды — бұл ${affordableResults} жарияланым. Ақылы дереккөз өткізіліп жіберілді.`,
      },
    };
  }

  return {
    ...base,
    verdict: 'ALLOWED',
    allowed: true,
    note: {
      ru: `Расход за сутки: ${money(spentCents)} $ из ${money(budgetCents)} $.`,
      kk: `Тәуліктік шығын: ${money(budgetCents)} $ ішінен ${money(spentCents)} $.`,
    },
  };
}

/**
 * Сколько результатов можно купить на остаток.
 *
 * Округление вниз — обратное тому, которым считается стоимость. Стоимость
 * округляется вверх, чтобы не пообещать дешевле, чем спишется; вместимость —
 * вниз, чтобы не пообещать больше, чем влезает. Оба округления ошибаются в
 * одну сторону: в пользу предела, а не в пользу прогона.
 */
export function maxAffordableResults(remainingUsd: number): number {
  if (!Number.isFinite(remainingUsd) || remainingUsd <= 0) return 0;
  const remainingCents = Math.round(remainingUsd * 100);
  return Math.floor((remainingCents * 1000) / APIFY_PRICE_PER_1000_CENTS);
}
