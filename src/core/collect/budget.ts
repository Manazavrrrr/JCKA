/**
 * Дневной предел расходов на платный сбор.
 *
 * Зачем понадобился. Пока платный источник запускался кнопкой, предела
 * хватало одного — потолка на прогон (MAX_POSTS_LIMIT, 27 центов). Худший
 * случай был виден целиком: человек ошибается один раз и тратит один раз.
 * Автоматический обход убирает человека из этой цепочки, и прежняя защита
 * перестаёт защищать: прогон по-прежнему стоит не больше 27 центов, но
 * прогонов теперь столько, сколько минут в сутках. Потолок на прогон без
 * потолка на сутки — это не предел расхода, а размер шага, которым расход
 * растёт.
 *
 * Поэтому здесь второй предел, и он считается за сутки, а не за прогон.
 *
 * Три решения, которые стоит объяснить, потому что они выглядят как мелочи.
 *
 * Первое: деньги считаются в центах целыми числами. Доллар в double — это
 * приглашение к расхождению: 0.1 + 0.2 даёт 0.30000000000000004, а сутки
 * автообхода складывают сотни таких слагаемых. Расхождение в сотую цента
 * никого не разорит, но превращает сравнение «потрачено < лимита» в лотерею
 * на самой границе, то есть ровно там, где этот модуль и должен отвечать
 * точно. Снаружи доллары, внутри целые центы.
 *
 * Второе: сутки местные, а не UTC. Орган работает в Усть-Каменогорске, и
 * «за сегодня» для аналитика начинается в полночь по его часам. На UTC
 * граница суток пришлась бы на пять утра местного времени, и расход, сделанный
 * ночью, лёг бы во вчерашний день. Смещение вынесено в именованную
 * постоянную, потому что это решение, а не свойство природы.
 *
 * Третье: времени модуль не знает. Текущий момент приходит параметром. Тест
 * на границу суток, который зависит от того, когда его запустили, — не тест,
 * а генератор случайных падений в ночную смену.
 *
 * Модуль чистый: ни сети, ни Prisma, ни Date.now().
 */

import type { Label } from '../domain/enums';

import { APIFY_PRICE_PER_1000_CENTS, estimateRunCostUsd } from './apify';

// ---------------------------------------------------------------------------
// Сутки
// ---------------------------------------------------------------------------

/**
 * Часовой пояс органа в минутах от UTC. Казахстан с марта 2024 года живёт в
 * одном поясе UTC+5, и Усть-Каменогорск в нём же.
 */
export const LOCAL_UTC_OFFSET_MINUTES = 5 * 60;

/**
 * Начало местных суток, в которые попадает указанный момент.
 *
 * Возвращается момент в UTC — тот самый, с которого следует считать расход.
 * Сравнивать даты строками («2026-10-18») здесь нельзя: строка местной даты и
 * строка даты UTC в пять часов расходятся, и расход за ночь потерялся бы.
 */
export function startOfLocalDay(now: Date): Date {
  const shifted = new Date(now.getTime() + LOCAL_UTC_OFFSET_MINUTES * 60_000);
  const midnightShifted = Date.UTC(
    shifted.getUTCFullYear(),
    shifted.getUTCMonth(),
    shifted.getUTCDate(),
  );
  return new Date(midnightShifted - LOCAL_UTC_OFFSET_MINUTES * 60_000);
}

// ---------------------------------------------------------------------------
// Предел
// ---------------------------------------------------------------------------

/**
 * Предел по умолчанию: половина доллара в сутки.
 *
 * Выбран не наугад. Бесплатный тариф Apify даёт 5 долларов в месяц; при
 * половине доллара в сутки месячный кредит кончился бы за десять дней, что
 * слишком быстро, — но это предел худшего случая, а не план расхода. Обычный
 * день автообхода стоит центы: повторы между прогонами отсеиваются по
 * отпечатку, и платить приходится только за новое.
 */
export const DEFAULT_DAILY_BUDGET_USD = 0.5;

/**
 * Потолок самого предела.
 *
 * Поле «дневной лимит» — это поле ввода, а поле ввода принимает лишний нуль.
 * Пять долларов в сутки — это весь месячный кредит бесплатного тарифа за один
 * день; больше этого ошибиться нельзя даже опечаткой.
 */
export const MAX_DAILY_BUDGET_USD = 5;

/** Приводит введённый предел к допустимому. Отрицательное — к нулю. */
export function clampDailyBudgetUsd(usd: number): number {
  if (!Number.isFinite(usd)) return DEFAULT_DAILY_BUDGET_USD;
  const cents = Math.round(usd * 100);
  const capped = Math.min(MAX_DAILY_BUDGET_USD * 100, Math.max(0, cents));
  return capped / 100;
}

// ---------------------------------------------------------------------------
// Расход за сутки
// ---------------------------------------------------------------------------

/** Прогон в том виде, в каком он нужен для счёта: когда и почём. */
export interface SpentRun {
  startedAt: Date;
  costUsd: number;
}

/**
 * Сколько потрачено с начала местных суток.
 *
 * Складывается в центах. Бесплатные прогоны (Telegram, демонстрационные на
 * образце) приходят сюда с нулевой стоимостью и на сумму не влияют — но
 * приходят, а не отфильтровываются вызывающим: пусть решение «это ничего не
 * стоило» принимается в одном месте.
 */
export function spentTodayUsd(runs: readonly SpentRun[], now: Date): number {
  const from = startOfLocalDay(now).getTime();
  let cents = 0;
  for (const run of runs) {
    if (run.startedAt.getTime() < from) continue;
    if (!Number.isFinite(run.costUsd) || run.costUsd <= 0) continue;
    cents += Math.round(run.costUsd * 100);
  }
  return cents / 100;
}

