/**
 * Нижняя граница длины термина.
 *
 * Две буквы — это «ЖК», настоящее и полезное слово-ловушка. Одна буква
 * при поиске по границам слова поймала бы предлоги и инициалы, и прогон
 * сбора превратился бы в выгрузку всего потока.
 */
export const MIN_TERM_LENGTH = 2;

/** Верхняя граница — защита от вставки целого абзаца вместо термина. */
export const MAX_TERM_LENGTH = 80;

export interface WatchTerm {
  id: string;
  category: WatchTermCategory;
  language: WatchTermLanguage;
  /** Термин в том виде, в каком его написал аналитик. */
  text: string;
  /** Выключенный термин хранится, но в прогоне сбора не участвует. */
  active: boolean;
  /** Зачем слово в списке — подсказка следующему аналитику. */
  note?: Label | null;
}

/**
 * Проверка термина на границе API.
 *
 * Звёздочка разрешена, остальные спецсимволы регулярных выражений при
 * компиляции экранируются, поэтому запрещать их не нужно — достаточно
 * не дать записать пустую строку или абзац.
 */
export const watchTermInputSchema = z.object({
  category: watchTermCategorySchema,
  language: watchTermLanguageSchema,
  text: z
    .string()
    .trim()
    .min(MIN_TERM_LENGTH, `Термин короче ${MIN_TERM_LENGTH} символов поймает слишком много`)
    .max(MAX_TERM_LENGTH, `Термин длиннее ${MAX_TERM_LENGTH} символов — это уже фраза, а не слово-ловушка`)
    .refine((value) => /[\p{L}\p{N}]/u.test(value), 'Термин должен содержать хотя бы одну букву или цифру'),
  active: z.boolean().default(true),
  note: z
    .object({ ru: z.string().trim().min(1), kk: z.string().trim().min(1) })
    .nullish(),
});

export type WatchTermInput = z.infer<typeof watchTermInputSchema>;

// ---------------------------------------------------------------------------
// Компиляция термина в шаблон
// ---------------------------------------------------------------------------

/**
 * Символы, которые в регулярном выражении означают не себя.
 *
 * Звёздочки в списке нет намеренно: это единственный символ, которому
 * в термине придан смысл — «любое окончание».
 */
const REGEXP_SPECIALS = /[.^$+?()[\]{}|\\/]/g;

/** Разделители слов внутри термина: пробел, дефис и оба тире. */
const WORD_SEPARATOR = '[\\s\\-–—]+';

/**
 * Превращает написанное аналитиком в источник регулярного выражения.
 *
 * Результат отдаётся в findPattern, который сам свернёт буквы шаблона
 * под свёрнутый текст и заменит `\b` и `\w` на варианты, понимающие
 * кириллицу. Поэтому здесь можно писать обычный синтаксис.
 */
export function termPatternSource(text: string): string {
  const words = text
    .trim()
    .split(/[\s–—-]+/)
    .filter((word) => word.length > 0);

  if (words.length === 0) return '';

  const body = words
    .map((word) => word.replace(REGEXP_SPECIALS, '\\$&').replaceAll('*', '\\w*'))
    .join(WORD_SEPARATOR);

  /**
   * Граница слова ставится только там, где рядом с ней стоит буква.
   *
   * Граница — это переход «не-буква → буква» или наоборот. Если термин
   * начинается или кончается знаком препинания, требовать такого перехода
   * бессмысленно: в «цена (от)» после закрывающей скобки стоит пробел,
   * оба символа не-буквы, перехода нет, и термин не совпал бы никогда.
   * Звёздочка считается буквенным краем: она превращается в `\w*`.
   */
  const first = words[0] ?? '';
  const last = words[words.length - 1] ?? '';
  const wordish = /[\p{L}\p{N}_*]/u;

  const prefix = wordish.test(first.charAt(0)) ? '\\b' : '';
  const suffix = wordish.test(last.charAt(last.length - 1)) ? '\\b' : '';

  return `${prefix}${body}${suffix}`;
}

/**
 * Кэш скомпилированных шаблонов.
 *
 * Прогон сбора — это сотни текстов на десятки терминов; перекомпиляция
 * одного и того же выражения на каждом пересечении заметна. Кэш не делает
 * модуль грязным: результат зависит только от текста термина.
 */
const patternCache = new Map<string, RegExp | null>();

export function compileTerm(text: string): RegExp | null {
  const cached = patternCache.get(text);
  if (cached !== undefined) return cached;

  const source = termPatternSource(text);
  let compiled: RegExp | null = null;

  if (source.length > 0) {
    try {
      compiled = new RegExp(source);
    } catch {
      // Сюда можно попасть только на экзотическом вводе, который пережил
      // экранирование. Термин молча не сработает, но прогон не упадёт.
      compiled = null;
    }
  }

  patternCache.set(text, compiled);
  return compiled;
}

// ---------------------------------------------------------------------------
// Поиск
// ---------------------------------------------------------------------------

export interface TermHit extends PatternHit {
  termId: string;
  termText: string;
  category: WatchTermCategory;
  /** Предложение целиком — цитата, которую видит аналитик. */
  quote: string;
  quoteStart: number;
  quoteEnd: number;
}

/**
 * Все срабатывания активных терминов в тексте, по порядку появления.
 *
 * Выключенные термины пропускаются здесь, а не на вызывающей стороне:
 * забыть про фильтр при подсчёте статистики проще, чем кажется.
 */
export function matchTerms(text: string, terms: readonly WatchTerm[]): TermHit[] {
  const hits: TermHit[] = [];

  for (const term of terms) {
    if (!term.active) continue;

    const pattern = compileTerm(term.text);
    if (!pattern) continue;

    for (const hit of findPattern(text, pattern)) {
      const sentence = expandToSentence(text, hit.charStart, hit.charEnd);
      hits.push({
        ...hit,
        termId: term.id,
        termText: term.text,
        category: term.category,
        quote: sentence.fragment,
        quoteStart: sentence.charStart,
        quoteEnd: sentence.charEnd,
      });
    }
  }

  return hits.sort((a, b) => a.charStart - b.charStart || a.charEnd - b.charEnd);
}

/** Уникальные термины из набора срабатываний, в порядке первого появления. */
export function distinctTerms(hits: readonly TermHit[]): TermHit[] {
  const seen = new Set<string>();
  const result: TermHit[] = [];

  for (const hit of hits) {
    if (seen.has(hit.termId)) continue;
    seen.add(hit.termId);
    result.push(hit);
  }

  return result;
}

/** Категории, сработавшие в наборе, в порядке объявления категорий. */
export function hitCategories(hits: readonly TermHit[]): WatchTermCategory[] {
  const present = new Set(hits.map((hit) => hit.category));
  return WATCH_TERM_CATEGORIES.filter((category) => present.has(category));
}
