/**
 * Слова-ловушки: чем система вылавливает объявления из потока.
 *
 * Зачем отдельная сущность. Поток публикаций по рынку жилья — это почти
 * целиком вторичка, аренда и посуточная сдача. Строящееся долевое жильё
 * в нём — узкая полоса, и ширину этой полосы задаёт не программист, а
 * аналитик: сегодня в области показательна «рассрочка от застройщика»,
 * через месяц — «клубный дом» или имя конкретного ЖК. Если список слов
 * зашит в код, каждая такая правка — это задача разработчику и новая сборка.
 * Поэтому слова-ловушки здесь — данные: их видно на экране, их правит
 * аналитик, и у каждого слова есть категория, язык и переключатель.
 *
 * Чем это отличается от словаря в src/core/ai. Тот словарь отвечает на
 * вопрос «какой риск виден в тексте» и предлагает факторы R2, R3, R5, R6.
 * Этот — на вопрос «стоит ли вообще тянуть этот текст в систему».
 * Разные задачи и разная цена ошибки: лишнее слово здесь означает мусор
 * в очереди аналитика, а не ошибочный балл в оценке объекта.
 *
 * Как пишется термин. Обычным словом, без регулярных выражений: «застройщик»,
 * «первоначальный взнос», «Алтай-Арман». Звёздочка в конце или середине
 * заменяет остаток слова: «рассрочк*» ловит «рассрочка», «рассрочку»,
 * «рассрочкой». Пробел внутри термина совпадает с любым пробельным набором
 * и с дефисом. Всё остальное — буквально, спецсимволы экранируются: аналитик
 * не может случайно уронить сбор, написав в термине скобку.
 *
 * Поиск идёт поверх примитивов из src/core/ai/text: та же посимвольная
 * свёртка (казахские буквы к русским, латинские подмены к кириллице) и те же
 * границы слова, понимающие кириллицу. Благодаря этому позиции совпадений
 * указывают на точные символы исходного текста, и найденное слово можно
 * подсветить ровно там, где оно стоит.
 *
 * Модуль чистый: ни Prisma, ни сети, ни текущего времени.
 */

