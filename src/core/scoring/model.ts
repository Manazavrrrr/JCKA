/**
 * Балл объекта.
 *
 * Формула ТЗ: min(100, сумма весов подтверждённых факторов).
 * На вход принимаются ТОЛЬКО коды факторов со статусом CONFIRMED —
 * фильтрация выполняется выше по стеку, в service.ts. Статусы
 * NEEDS_CHECK, REJECTED и NOT_APPLICABLE дают 0 баллов.
 *
 * Дубликаты кодов игнорируются: один фактор может быть засчитан лишь однажды.
 */
export function computeScore(confirmedCodes: readonly FactorCode[]): number {
  const unique = new Set(confirmedCodes);
  let sum = 0;
  for (const code of unique) {
    sum += FACTOR_WEIGHTS[code];
  }
  return Math.min(MAX_SCORE, sum);
}

/**
 * Проверяет наличие комбинации, открывающей красную зону.
 */
export function hasRedZoneCombination(confirmedCodes: readonly FactorCode[]): boolean {
  const unique = new Set(confirmedCodes);
  return RED_ZONE_COMBINATION.every((code) => unique.has(code));
}

/**
 * Зона риска.
 *
 * Правило из раздела 5 ТЗ:
 *   - красная  — 60+ баллов И одновременно подтверждены R1 и R2;
 *   - жёлтая   — 25–59 баллов, а также 60+ без комбинации R1+R2;
 *   - зелёная  — 0–24 балла.
 *
 * Обрати внимание: зона — функция от двух аргументов, а не от одного балла.
 * Объект с 75 баллами без подтверждённого R2 остаётся жёлтым.
 */
export function resolveZone(score: number, confirmedCodes: readonly FactorCode[]): RiskZone {
  if (score >= RED_THRESHOLD && hasRedZoneCombination(confirmedCodes)) {
    return 'RED';
  }
  if (score >= YELLOW_THRESHOLD) {
    return 'YELLOW';
  }
  return 'GREEN';
}

/**
 * Разница готовности в процентных пунктах.
 * Возвращает null, если любое из значений не задано: неизвестные сведения
 * не должны превращаться в фактор.
 */
export function readinessGapPp(
  declaredPct: number | null | undefined,
  verifiedPct: number | null | undefined,
): number | null {
  if (declaredPct == null || verifiedPct == null) return null;
  return Math.abs(declaredPct - verifiedPct);
}

/**
 * Достигнут ли порог R5. Null означает «недостаточно данных», а не «нет».
 */
export function meetsReadinessGapThreshold(
  declaredPct: number | null | undefined,
  verifiedPct: number | null | undefined,
): boolean | null {
  const gap = readinessGapPp(declaredPct, verifiedPct);
  if (gap === null) return null;
  return gap >= READINESS_GAP_THRESHOLD_PP;
}

/** Упорядоченный список кодов — для стабильного вывода в отчётах и тестах. */
export function sortFactorCodes(codes: readonly FactorCode[]): FactorCode[] {
  const order = new Map(FACTOR_CODES.map((code, index) => [code, index]));
  return [...new Set(codes)].sort((a, b) => (order.get(a) ?? 0) - (order.get(b) ?? 0));
}
