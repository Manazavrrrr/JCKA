/**
 * Мост между ошибками слоя запросов и страницами.
 *
 * Запросы сообщают об отсутствии записи через HttpError('NOT_FOUND') —
 * так же, как для API, потому что одна и та же функция обслуживает и
 * маршрут, и страницу. Странице этого недостаточно: Next различает
 * «нет такой страницы» и «страница упала», и показывает разные экраны.
 *
 * Отдельный помощник нужен ровно для того, чтобы ни одна страница не
 * обошлась голым catch. Голый catch превращает сбой базы в 404: аналитик
 * видит «объекта нет» и идёт искать, кто его удалил, вместо того чтобы
 * узнать, что система не отвечает. Здесь перехватывается только
 * NOT_FOUND, всё остальное пробрасывается в обработчик ошибок Next.
 */

import { notFound } from 'next/navigation';

import { HttpError } from './http';

export async function orNotFound<T>(promise: Promise<T>): Promise<T> {
  try {
    return await promise;
  } catch (error) {
    if (error instanceof HttpError && error.code === 'NOT_FOUND') notFound();
    throw error;
  }
}
