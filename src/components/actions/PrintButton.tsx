'use client';

/**
 * Кнопка печати.
 *
 * Единственная причина, по которой это отдельный клиентский компонент, —
 * window.print(). Ничего, кроме вызова печати, здесь происходить не должно:
 * карточка уже сверстана так, чтобы печаталась сама (@media print в
 * globals.css убирает навигацию и кнопки). Если бы кнопка открывала
 * «версию для печати» отдельной страницей, появился бы второй шаблон
 * документа, который рано или поздно разошёлся бы с первым.
 */

export function PrintButton({ label }: { label: string }) {
  return (
    <button type="button" className="btn no-print" onClick={() => window.print()}>
      {label}
    </button>
  );
}
