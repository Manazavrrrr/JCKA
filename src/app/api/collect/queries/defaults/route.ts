/**
 * POST /api/collect/queries/defaults — вернуть набор слов по умолчанию.
 *
 * Почему отдельный маршрут, а не признак в теле добавления. Добавление слова
 * принимает то, что ввёл человек, и отвечает за одно слово; возврат набора
 * ничего не принимает и отвечает за список целиком. Признак в общем теле
 * сделал бы из двух разных действий одно с ветвлением — и тогда опечатка в
 * признаке превращала бы «добавить слово» в «долить набор».
 *
 * Тела у запроса нет намеренно. Набор по умолчанию лежит в ядре
 * (`src/core/collect/discovery.ts`), и давать его списком снаружи значило бы
 * завести второй набор по умолчанию — тот, что пришёл в запросе.
 *
 * Ответ 200, а не 201: действие идемпотентно по смыслу. Второе нажатие
 * ничего не создаёт и честно отвечает, что все слова набора уже на месте.
 */

import { prisma } from '../../../../../lib/db';
import { restoreDefaultSearchQueries } from '../../../../../server/discovery';
import { actorFrom } from '../../../../../server/http';
import { route } from '../../../../../server/route';

export const dynamic = 'force-dynamic';

export const POST = route(async (request) => {
  return restoreDefaultSearchQueries(prisma, actorFrom(request.headers));
});
